def run_tests():
    checks=[]
    def check(name, fn):
        fn();checks.append({"name":name,"status":"PASS"})
    # OLS exactness and shape
    def test_ols():
        rng=np.random.default_rng(100);xx=rng.normal(size=(300,2));yy=1.2+xx@np.array([.4,-.8])+rng.normal(0,.1,300)
        mod=fit_ols(xx,yy);mu,_=predict_ols(mod,xx);assert np.sqrt(np.mean((yy-mu)**2))<.13;assert mod["rank"]==3
    check("OLS fit and residual scale",test_ols)
    def test_seed():
        d1=generate_dataset(2,25,seed=77);d2=generate_dataset(2,25,seed=77)
        assert np.array_equal(d1["x"],d2["x"]);assert np.array_equal(d1["fabric"],d2["fabric"])
    check("Deterministic seeded generation",test_seed)
    def test_bounds():
        d=generate_dataset(3,40,seed=78)
        assert np.isfinite(d["y"]).all();assert set(np.unique(d["fabric"])).issubset({0,1,2});assert len(d["x"])==len(d["y"])
    check("Dataset shapes and finite values",test_bounds)
    def test_label_accuracy():
        d=generate_dataset(100,100,state_probs=(1/3,1/3,1/3),seed=91,label_accuracy=.90,phi=.0)
        assert np.mean(d["fabric"]==d["state"])>.87
    check("Fabric-label noise process",test_label_accuracy)
    def test_feature_shapes():
        d=generate_dataset(2,50,seed=92)
        assert features(d,"Single proxy").shape==(100,1)
        assert features(d,"Multi-proxy").shape==(100,3)
        assert features(d,"Channel-aware").shape==(100,5)
    check("Decoder feature dimensions",test_feature_shapes)
    def test_posterior_positive():
        d=generate_dataset(8,60,seed=93);m=fit_ols(features(d,"Channel-aware"),d["x"]);mu,se=predict_ols(m,features(d,"Channel-aware"))
        assert np.all(np.isfinite(mu)) and np.all(se>0)
    check("Finite predictions and positive predictive uncertainty",test_posterior_positive)
    def test_invalid_args():
        failed=False
        try: generate_dataset(0,20)
        except (ValueError,IndexError): failed=True
        assert failed
    check("Invalid empty dataset rejected explicitly",test_invalid_args)
    def test_invalid_probs():
        for probs in [(0,0,0),(-1,1,1),(float("nan"),0,1),(0,1)]:
            try: generate_dataset(2,20,state_probs=probs)
            except ValueError: pass
            else: raise AssertionError(f"invalid probabilities accepted: {probs}")
    check("Invalid channel probabilities rejected",test_invalid_probs)
    def test_geometry():
        A=np.array([[1.0,.86,-.20],[.70,-.43,.66],[.42,.24,-.78]])
        sv=np.linalg.svd(A,compute_uv=False);assert sv[0]>0 and sv[-1]>0
    check("Illustrative proxy-response matrix full rank",test_geometry)
