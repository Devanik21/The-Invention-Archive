def _state_sequence(rng: np.random.Generator, n: int, probs: np.ndarray, stay: float = 0.94) -> np.ndarray:
    out = np.zeros(n, dtype=int)
    out[0] = rng.choice(3, p=probs)
    for t in range(1, n):
        if rng.random() < stay:
            out[t] = out[t-1]
        else:
            out[t] = rng.choice(3, p=probs)
    return out


def generate_dataset(n_caves: int, steps: int, state_probs=(0.55, 0.27, 0.18), alteration_scale=1.0,
                     seed=SEED, label_accuracy=0.90, phi=0.78):
    """Generate synthetic cave sequences with climate, alteration, and noisy fabric labels.

    Raises ValueError for invalid dimensions or channel probabilities rather than
    relying on a downstream indexing failure.
    """
    if not isinstance(n_caves, (int, np.integer)) or n_caves < 1:
        raise ValueError("n_caves must be a positive integer")
    if not isinstance(steps, (int, np.integer)) or steps < 2:
        raise ValueError("steps must be an integer of at least 2")
    probs = np.asarray(state_probs, dtype=float)
    if probs.shape != (3,) or not np.isfinite(probs).all() or np.any(probs < 0) or probs.sum() <= 0:
        raise ValueError("state_probs must contain three finite, nonnegative values with positive sum")
    if not 0 <= label_accuracy <= 1 or not -0.999 < phi < 0.999:
        raise ValueError("label_accuracy must be in [0,1] and phi in (-0.999,0.999)")
    rng = np.random.default_rng(seed)
    probs = probs / probs.sum()
    xs, ys, fobs, ftrue, cave_ids, times = [], [], [], [], [], []
    climate_loading = np.array([1.00, 0.70, 0.42])
    diagenetic_loading = np.array([0.86, -0.43, 0.24])
    microbial_loading = np.array([-0.20, 0.66, -0.78])
    for cave in range(n_caves):
        x = np.zeros(steps)
        x[0] = rng.normal()
        for t in range(1, steps):
            x[t] = phi*x[t-1] + math.sqrt(1-phi**2)*rng.normal()
        state = _state_sequence(rng, steps, probs)
        # Correlated, nonstationary channel disturbances: a smooth alteration burden
        # and an autocorrelated microbial signal. These are assumed synthetic mechanisms.
        zd = np.zeros(steps); zm = np.zeros(steps)
        zd[0] = rng.normal(0.70, 0.22); zm[0] = rng.normal(0.55, 0.30)
        for t in range(1, steps):
            zd[t] = 0.68 + 0.72*(zd[t-1]-0.68) + 0.22*rng.normal()
            zm[t] = 0.53 + 0.55*(zm[t-1]-0.53) + 0.30*rng.normal()
        background = rng.normal(0.0, 0.34, size=(steps, 3))
        y = x[:,None]*climate_loading[None,:] + background
        y += (state==1)[:,None] * (alteration_scale*zd[:,None]*diagenetic_loading[None,:])
        y += (state==2)[:,None] * (alteration_scale*zm[:,None]*microbial_loading[None,:])
        # Observed fabric is a noisy proxy for a three-state channel classification.
        fo = state.copy()
        mask = rng.random(steps) > label_accuracy
        for k in np.where(mask)[0]:
            fo[k] = rng.choice([s for s in range(3) if s != state[k]])
        xs.append(x); ys.append(y); fobs.append(fo); ftrue.append(state)
        cave_ids.extend([cave]*steps); times.extend(range(steps))
    return {"x":np.concatenate(xs), "y":np.vstack(ys), "fabric":np.concatenate(fobs),
            "state":np.concatenate(ftrue), "cave":np.asarray(cave_ids), "time":np.asarray(times)}


def features(ds, method):
    y = ds["y"]
    if method == "Single proxy":
        return y[:, :1]
    if method == "Multi-proxy":
        return y
    # Reference fabric class is the implicit baseline; omit one dummy to avoid exact collinearity.
    f = ds["fabric"]
    return np.column_stack([y, (f==1).astype(float), (f==2).astype(float)])


def fit_ols(x: np.ndarray, y: np.ndarray):
    X = np.column_stack([np.ones(len(x)), x])
    beta, _, rank, _ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    dof = max(1, len(y) - rank)
    sigma2 = float(resid @ resid / dof)
    xtxi = np.linalg.pinv(X.T @ X)
    return {"beta":beta, "sigma2":sigma2, "xtxi":xtxi, "rank":int(rank), "dof":dof}


def predict_ols(model, x: np.ndarray):
    X = np.column_stack([np.ones(len(x)), x])
    mu = X @ model["beta"]
    # Gaussian linear-model predictive standard error; not a full hierarchical posterior.
    h = np.einsum("ij,jk,ik->i", X, model["xtxi"], X)
    se = np.sqrt(np.maximum(model["sigma2"]*(1.0+h), 0.0))
    return mu, se


def metrics(y, mu, se):
    err = y-mu
    cover = np.abs(err) <= 1.6448536269514722*se
    return {"rmse":float(np.sqrt(np.mean(err**2))), "mae":float(np.mean(np.abs(err))),
            "coverage90":float(np.mean(cover)), "width90":float(np.mean(2*1.6448536269514722*se)),
            "gaussian_nll":float(np.mean(0.5*np.log(2*np.pi*se**2)+0.5*(err/se)**2))}


def benchmark():
    train = generate_dataset(72, 170, seed=SEED)
    tests = {
        "In-distribution": generate_dataset(20, 170, seed=SEED+1),
        "Shifted alteration": generate_dataset(20, 170, state_probs=(0.22,0.60,0.18), alteration_scale=1.45, seed=SEED+2)
    }
    rows=[]; fitted={}
    for method in METHODS:
        model=fit_ols(features(train,method),train["x"]); fitted[method]=model
        for scenario, test in tests.items():
            mu,se=predict_ols(model,features(test,method))
            m=metrics(test["x"],mu,se)
            rows.append({"method":method,"scenario":scenario,**m,"n_test":len(mu)})
    with (RES/"benchmark_metrics.csv").open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=rows[0].keys());w.writeheader();w.writerows(rows)
    # Sensitivity: models remain trained at the nominal setting; test contamination varies.
    sens=[]
    for scale in np.linspace(0,2.0,9):
        test=generate_dataset(18,150,state_probs=(0.30,0.52,0.18),alteration_scale=float(scale),seed=SEED+100+int(scale*100))
        for method in METHODS:
            mu,se=predict_ols(fitted[method],features(test,method))
            m=metrics(test["x"],mu,se)
            sens.append({"alteration_scale":float(scale),"method":method,**m,"n_test":len(mu)})
    with (RES/"sensitivity_sweep.csv").open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=sens[0].keys());w.writeheader();w.writerows(sens)
    ex=generate_dataset(1,180,state_probs=(0.55,0.27,0.18),seed=SEED+10)
    exrows=[]
    for t in range(len(ex["x"])):
        row={"time":int(ex["time"][t]),"climate_true":float(ex["x"][t]),"fabric_observed":int(ex["fabric"][t]),"state_synthetic":int(ex["state"][t])}
        for j in range(3): row[f"proxy_{j+1}"]=float(ex["y"][t,j])
        for method in METHODS:
            mu,se=predict_ols(fitted[method],features({k:(v[t:t+1] if isinstance(v,np.ndarray) and v.shape[0]==len(ex["x"]) else v) for k,v in ex.items()},method))
            key=method.lower().replace("-","_").replace(" ","_")
            row[f"{key}_mean"]=float(mu[0]);row[f"{key}_sd"]=float(se[0])
        exrows.append(row)
    with (RES/"example_series.csv").open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=exrows[0].keys());w.writeheader();w.writerows(exrows)
    spec={"status":"synthetic model-generated benchmark; not empirical cave data",
          "seed":SEED,"training_caves":72,"training_steps_per_cave":170,
          "test_caves_per_scenario":20,"test_steps_per_cave":170,
          "climate_ar1_phi":0.78,"label_accuracy_assumed":0.90,
          "training_state_probabilities":[0.55,0.27,0.18],
          "shifted_state_probabilities":[0.22,0.60,0.18],"shifted_alteration_scale":1.45,
          "climate_loadings":[1.0,0.70,0.42],"diagenetic_loadings":[0.86,-0.43,0.24],
          "microbial_loadings":[-0.20,0.66,-0.78],"background_noise_sd":0.34,
          "note":"Parameters are illustrative assumptions chosen to stress test identifiability, not fitted to cave measurements."}
    (RES/"synthetic_generation_spec.json").write_text(json.dumps(spec,indent=2)+"\n",encoding="utf-8")
    return rows,sens,exrows


