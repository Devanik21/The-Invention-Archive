#!/usr/bin/env python3
"""Reproducible synthetic benchmark for risk-budgeted Floquet pulse design.

This is a small open-qubit testbed, not a hardware experiment and not an RL/Neural-SDE
implementation. It compares a constant resonant pulse with an offline robust search
within a bounded two-harmonic Fourier family, passed through a first-order hardware
low-pass filter. Quasi-static detuning uncertainty and Lindblad relaxation/dephasing
are explicit. All reported numbers and figures are regenerated by this file.

Dependencies: Python >=3.10, numpy, scipy, matplotlib.
"""
from __future__ import annotations
import json
import math
import platform
from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import minimize
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent
FIG = ROOT / "figures"
RES = ROOT / "results"
FIG.mkdir(exist_ok=True)
RES.mkdir(exist_ok=True)

# Two-level rotating-frame model, hbar=1.
I2 = np.eye(2, dtype=complex)
SX = np.array([[0, 1], [1, 0]], dtype=complex)
SZ = np.array([[1, 0], [0, -1]], dtype=complex)
SM = np.array([[0, 1], [0, 0]], dtype=complex)  # |0><1| relaxation
P1 = np.array([[0, 0], [0, 1]], dtype=complex)
N_CYCLES = 3
PERIOD = 2.0
OMEGA = 2.0 * np.pi / PERIOD
T_FINAL = N_CYCLES * PERIOD
U0 = np.pi / T_FINAL                 # area-pi baseline in the zero-drift, no-noise limit
TAU_HW = 0.075                       # dimensionless model time units
GAMMA_1 = 0.004                      # relaxation rate
GAMMA_PHI = 0.006                    # pure-dephasing rate
DT = 0.005
COEFF_BOUND = 0.09
U_MAX = 1.0
SLEW_MAX = 1.5


def dissipator(L: np.ndarray, rho: np.ndarray) -> np.ndarray:
    LdL = L.conj().T @ L
    return L @ rho @ L.conj().T - 0.5 * (LdL @ rho + rho @ LdL)


def fourier_input(t: float, c: np.ndarray) -> float:
    a1, b1, a2, b2 = c
    return float(U0 + a1*np.cos(OMEGA*t) + b1*np.sin(OMEGA*t)
                 + a2*np.cos(2*OMEGA*t) + b2*np.sin(2*OMEGA*t))


def coupled_rhs(t: float, rho: np.ndarray, v: float, delta: float, c: np.ndarray,
                gamma_phi: float = GAMMA_PHI, gamma_1: float = GAMMA_1):
    H = 0.5 * delta * SZ + 0.5 * v * SX
    drho = -1j * (H @ rho - rho @ H)
    drho += gamma_1 * dissipator(SM, rho)
    drho += 0.5 * gamma_phi * (SZ @ rho @ SZ - rho)
    dv = (fourier_input(t, c) - v) / TAU_HW
    return drho, dv


def rk4_episode(delta: float, c: np.ndarray, dt: float = DT,
                gamma_phi: float = GAMMA_PHI, gamma_1: float = GAMMA_1,
                keep_trace: bool = False):
    steps = int(round(T_FINAL / dt))
    dt = T_FINAL / steps
    rho = np.array([[1, 0], [0, 0]], dtype=complex)
    v = U0
    traces = []
    for j in range(steps):
        t = j * dt
        k1r, k1v = coupled_rhs(t, rho, v, delta, c, gamma_phi, gamma_1)
        k2r, k2v = coupled_rhs(t + dt/2, rho + dt*k1r/2, v + dt*k1v/2,
                               delta, c, gamma_phi, gamma_1)
        k3r, k3v = coupled_rhs(t + dt/2, rho + dt*k2r/2, v + dt*k2v/2,
                               delta, c, gamma_phi, gamma_1)
        k4r, k4v = coupled_rhs(t + dt, rho + dt*k3r, v + dt*k3v,
                               delta, c, gamma_phi, gamma_1)
        rho = rho + dt*(k1r + 2*k2r + 2*k3r + k4r)/6
        v = v + dt*(k1v + 2*k2v + 2*k3v + k4v)/6
        if keep_trace:
            traces.append((t + dt, rho.copy(), v, fourier_input(t + dt, c)))
    fidelity = float(np.real(np.trace(P1 @ rho)))
    if keep_trace:
        return fidelity, rho, np.asarray(traces, dtype=object)
    return fidelity, rho


def cvar(losses: np.ndarray, alpha: float = 0.8) -> float:
    losses = np.asarray(losses, dtype=float)
    q = float(np.quantile(losses, alpha))
    tail = losses[losses >= q]
    return float(np.mean(tail)) if tail.size else q


def admissibility(c: np.ndarray):
    a1, b1, a2, b2 = map(float, c)
    amp_bound = U0 + math.hypot(a1, b1) + math.hypot(a2, b2)
    slew_bound = OMEGA*math.hypot(a1, b1) + 2*OMEGA*math.hypot(a2, b2)
    return amp_bound, slew_bound


def objective(c: np.ndarray, detunings: np.ndarray) -> float:
    amp, slew = admissibility(c)
    # Smooth finite-ensemble risk objective, with explicit conservative envelope constraints.
    if amp > U_MAX or slew > SLEW_MAX:
        return 10.0 + 10.0*max(0.0, amp-U_MAX)**2 + 10.0*max(0.0, slew-SLEW_MAX)**2
    losses = np.array([1.0-rk4_episode(float(d), c)[0] for d in detunings])
    return float(np.mean(losses) + 0.6*cvar(losses, 0.8) + 0.015*np.dot(c, c))


def main():
    train_delta = np.array([-0.18, -0.09, 0.0, 0.09, 0.18])
    test_delta = np.linspace(-0.28, 0.28, 29)
    baseline = np.zeros(4, dtype=float)
    opt = minimize(objective, x0=np.array([0.0, 0.0, 0.0, 0.0]),
                   args=(train_delta,), method="L-BFGS-B",
                   bounds=[(-COEFF_BOUND, COEFF_BOUND)]*4,
                   options={"maxiter": 65, "ftol": 1e-11, "gtol": 1e-7, "maxls": 25})
    coeff = np.asarray(opt.x, dtype=float)

    f_base = np.array([rk4_episode(float(d), baseline)[0] for d in test_delta])
    f_opt = np.array([rk4_episode(float(d), coeff)[0] for d in test_delta])
    losses_train = np.array([1-rk4_episode(float(d), coeff)[0] for d in train_delta])
    mean_base, mean_opt = float(np.mean(f_base)), float(np.mean(f_opt))
    worst_base, worst_opt = float(np.min(f_base)), float(np.min(f_opt))

    # Noise sweep at nominal detuning: model-generated, not experimental.
    phi_grid = np.array([0.0, 0.003, 0.006, 0.012, 0.024, 0.040])
    nf_base = np.array([rk4_episode(0.0, baseline, gamma_phi=float(g))[0] for g in phi_grid])
    nf_opt = np.array([rk4_episode(0.0, coeff, gamma_phi=float(g))[0] for g in phi_grid])

    # Waveform and filtered output at the reference (zero-drift) trajectory.
    f0, rho0, trace = rk4_episode(0.0, coeff, keep_trace=True)
    t = np.array([row[0] for row in trace], dtype=float)
    v = np.array([row[2] for row in trace], dtype=float)
    u = np.array([row[3] for row in trace], dtype=float)
    rho_eigs = np.linalg.eigvalsh(rho0)
    amp_bound, slew_bound = admissibility(coeff)

    # Checks: generator preserves trace and Hermiticity; propagated state is physical.
    rho_test = np.array([[0.63, 0.12+0.07j], [0.12-0.07j, 0.37]], dtype=complex)
    dtest, _ = coupled_rhs(0.37, rho_test, U0, 0.0, baseline)
    trace_derivative = abs(np.trace(dtest))
    herm_error = float(np.linalg.norm(dtest-dtest.conj().T))
    state_trace_error = abs(np.trace(rho0)-1.0)
    state_herm_error = float(np.linalg.norm(rho0-rho0.conj().T))
    min_eig = float(np.min(rho_eigs))
    fine_fid = rk4_episode(0.0, coeff, dt=DT/2)[0]
    convergence_error = abs(fine_fid-f0)

    # Recalculate waveform constraints on a dense time grid (actual filtered hardware output).
    dense_t = np.linspace(0, T_FINAL, 3001)
    dense_u = np.array([fourier_input(float(tt), coeff) for tt in dense_t])
    dense_du = np.gradient(dense_u, dense_t)
    actual_amp = float(np.max(np.abs(dense_u)))
    actual_slew = float(np.max(np.abs(dense_du)))

    checks = {
        "finite_and_normalized": bool(np.isfinite(f_base).all() and np.isfinite(f_opt).all()
                                       and abs(np.trace(rho0)-1) < 2e-8),
        "generator_trace_preserving": bool(trace_derivative < 1e-12),
        "generator_hermiticity_preserving": bool(herm_error < 1e-12),
        "state_hermiticity": bool(state_herm_error < 2e-8),
        "state_positive_semidefinite_with_tolerance": bool(min_eig > -2e-8),
        "control_amplitude_envelope": bool(amp_bound <= U_MAX+1e-10 and actual_amp <= U_MAX+2e-3),
        "control_slew_envelope": bool(slew_bound <= SLEW_MAX+1e-10 and actual_slew <= SLEW_MAX+2e-2),
        "time_step_convergence": bool(convergence_error < 2e-5),
        "optimizer_returned_finite_candidate": bool(np.isfinite(opt.fun) and np.isfinite(coeff).all()),
    }
    if not all(checks.values()):
        raise AssertionError("One or more verification checks failed: " + str(checks))

    # Figure 1: proposed architecture schematic.
    fig, ax = plt.subplots(figsize=(10.5, 4.1))
    ax.set_xlim(0, 10.5); ax.set_ylim(0, 4.1); ax.axis("off")
    boxes = [
        (0.25, 2.55, 2.0, 1.0, "Measurements\nparity / homodyne /\nsyndrome summaries"),
        (2.7, 2.55, 2.0, 1.0, "Neural-SDE belief\nlatent drift + rates\nposterior uncertainty"),
        (5.15, 2.55, 2.0, 1.0, "Risk-sensitive policy\nCVaR + logical loss\nheating budget"),
        (7.6, 2.55, 2.55, 1.0, "Admissible Floquet drive\nFourier coefficients\nfilter + amplitude / slew"),
        (5.15, 0.45, 2.0, 1.0, "Open-system plant\nLindblad evolution\nFloquet map"),
        (2.7, 0.45, 2.0, 1.0, "Diagnostics\nfidelity / leakage\nabsorbed work"),
        (7.6, 0.45, 2.55, 1.0, "Safety monitor\ninterlock / limits\naction authorization"),
    ]
    for x,y,w,h,txt in boxes:
        ax.add_patch(plt.Rectangle((x,y),w,h,facecolor="#edf3f8",edgecolor="#29465b",lw=1.4, zorder=2))
        ax.text(x+w/2,y+h/2,txt,ha="center",va="center",fontsize=8.5,color="#152c3b")
    arrows = [((2.25,3.05),(2.7,3.05)),((4.7,3.05),(5.15,3.05)),((7.15,3.05),(7.6,3.05)),
              ((8.85,2.55),(6.8,1.45)),((5.15,0.95),(4.7,0.95)),((3.7,1.45),(3.7,2.55)),
              ((7.15,0.95),(7.6,0.95)),((8.85,1.45),(6.2,2.55))]
    for p1,p2 in arrows:
        ax.annotate("",xy=p2,xytext=p1,arrowprops=dict(arrowstyle="->",lw=1.25,color="#405b6b"))
    ax.text(5.25,3.88,"PROPOSED CLOSED-LOOP CONTROL ARCHITECTURE",ha="center",fontsize=11,weight="bold",color="#18374b")
    fig.tight_layout(); fig.savefig(FIG/"fig01_architecture.png",dpi=220,bbox_inches="tight"); fig.savefig(FIG/"fig01_architecture.pdf",bbox_inches="tight"); plt.close(fig)

    # Figure 2: waveform input and first-order filtered drive.
    fig, ax = plt.subplots(figsize=(9.3,3.6))
    ax.plot(t,u,label="commanded Fourier drive",lw=1.2)
    ax.plot(t,v,label="filtered hardware output",lw=1.8)
    ax.axhline(U_MAX,ls="--",lw=.8,color="grey"); ax.axhline(-U_MAX,ls="--",lw=.8,color="grey")
    ax.set_xlabel("time (model units)"); ax.set_ylabel("drive amplitude (model units)")
    ax.set_title("Two-harmonic command after a first-order hardware filter")
    ax.legend(frameon=True,framealpha=.88,fontsize=8,loc="upper right",ncol=1); ax.grid(alpha=.22); fig.tight_layout()
    fig.savefig(FIG/"fig02_filtered_waveform.png",dpi=220); fig.savefig(FIG/"fig02_filtered_waveform.pdf"); plt.close(fig)

    # Figure 3: generalization across held-out quasi-static detuning.
    fig, ax = plt.subplots(figsize=(8.6,3.7))
    ax.plot(test_delta,f_base,label="constant resonant pulse",lw=1.6)
    ax.plot(test_delta,f_opt,label="risk-weighted multi-tone candidate",lw=1.8)
    ax.scatter(train_delta,[rk4_episode(float(d),coeff)[0] for d in train_delta],s=22,label="training detunings",zorder=3)
    ax.set_xlabel("static detuning δ (model units)"); ax.set_ylabel("final target-state population")
    ax.set_ylim(0,1.02); ax.set_title("Synthetic robustness test across detuning")
    ax.legend(frameon=False,fontsize=8); ax.grid(alpha=.22); fig.tight_layout()
    fig.savefig(FIG/"fig03_robustness.png",dpi=220); fig.savefig(FIG/"fig03_robustness.pdf"); plt.close(fig)

    # Figure 4: sensitivity to Markovian pure dephasing.
    fig, ax = plt.subplots(figsize=(8.6,3.7))
    ax.plot(phi_grid,nf_base,marker="o",label="constant resonant pulse")
    ax.plot(phi_grid,nf_opt,marker="s",label="risk-weighted multi-tone candidate")
    ax.set_xlabel("pure-dephasing rate γφ (model units)"); ax.set_ylabel("final target-state population")
    ax.set_ylim(0,1.02); ax.set_title("Synthetic dephasing sweep at zero detuning")
    ax.legend(frameon=False,fontsize=8); ax.grid(alpha=.22); fig.tight_layout()
    fig.savefig(FIG/"fig04_dephasing_sweep.png",dpi=220); fig.savefig(FIG/"fig04_dephasing_sweep.pdf"); plt.close(fig)

    metrics = {
        "status": "PASS" if all(checks.values()) else "FAIL",
        "scope": "synthetic open-qubit benchmark; not experimental data; not RL/Neural-SDE implementation",
        "python": platform.python_version(),
        "numpy": np.__version__,
        "scipy": scipy.__version__,
        "matplotlib": matplotlib.__version__,
        "time_step": DT,
        "time_step_half": DT/2,
        "period": PERIOD,
        "cycles": N_CYCLES,
        "final_time": T_FINAL,
        "carrier_angular_frequency": OMEGA,
        "hardware_filter_time_constant": TAU_HW,
        "relaxation_rate": GAMMA_1,
        "pure_dephasing_rate": GAMMA_PHI,
        "training_detunings": train_delta.tolist(),
        "test_detunings": test_delta.tolist(),
        "optimized_fourier_coefficients_a1_b1_a2_b2": coeff.tolist(),
        "optimizer_success_flag": bool(opt.success),
        "optimizer_message": str(opt.message),
        "objective_value": float(opt.fun),
        "mean_test_fidelity_constant": mean_base,
        "mean_test_fidelity_multitone": mean_opt,
        "worst_test_fidelity_constant": worst_base,
        "worst_test_fidelity_multitone": worst_opt,
        "actual_command_peak": actual_amp,
        "actual_command_slew_peak": actual_slew,
        "conservative_amplitude_bound": amp_bound,
        "conservative_slew_bound": slew_bound,
        "zero_detuning_final_fidelity": f0,
        "zero_detuning_final_density_eigenvalues": rho_eigs.real.tolist(),
        "time_step_convergence_abs_error": convergence_error,
        "pure_dephasing_sweep": phi_grid.tolist(),
        "dephasing_fidelity_constant": nf_base.tolist(),
        "dephasing_fidelity_multitone": nf_opt.tolist(),
        "checks": checks,
        "note": "An offline optimizer is used only as an executable control-design surrogate. No reinforcement-learning agent, neural SDE, many-body system, bosonic code, time crystal, or hardware experiment is simulated."
    }
    (RES/"verification_metrics.json").write_text(json.dumps(metrics,indent=2)+"\n",encoding="utf-8")
    np.savetxt(RES/"detuning_sweep.csv",np.column_stack([test_delta,f_base,f_opt]),delimiter=",",
               header="detuning,constant_pulse_fidelity,multitone_fidelity",comments="")
    np.savetxt(RES/"dephasing_sweep.csv",np.column_stack([phi_grid,nf_base,nf_opt]),delimiter=",",
               header="pure_dephasing_rate,constant_pulse_fidelity,multitone_fidelity",comments="")
    np.savetxt(RES/"waveform.csv",np.column_stack([t,u,v]),delimiter=",",
               header="time,commanded_drive,filtered_drive",comments="")
    print("SYNTHETIC OPEN-QUBIT VERIFICATION")
    print("---------------------------------")
    for k,vv in checks.items(): print(f"{'PASS' if vv else 'FAIL'}  {k}")
    print(f"optimizer_success_flag={opt.success}")
    print(f"coefficients={coeff.tolist()}")
    print(f"mean_test_fidelity_constant={mean_base:.8f}")
    print(f"mean_test_fidelity_multitone={mean_opt:.8f}")
    print(f"worst_test_fidelity_constant={worst_base:.8f}")
    print(f"worst_test_fidelity_multitone={worst_opt:.8f}")
    print(f"amplitude_bound={amp_bound:.8f}; slew_bound={slew_bound:.8f}")
    print(f"convergence_abs_error={convergence_error:.3e}")
    print("NOTE: Synthetic model outputs only; no experiment or full AI architecture validated.")

if __name__ == "__main__":
    main()
